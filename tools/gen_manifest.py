#!/usr/bin/env python3
"""gen_manifest.py — provenance for every ported file.

The port is a 158k-line translation measured against a moving reference: gdtk is
read-only for this work but it is a live checkout, so a file can change upstream
after its port lands. Each record here binds a C++ file to the exact D blob it
came from, and tools/check_staleness.sh re-hashes the D tree to report drift.

Origin is derived from path convention (src/nm/bbla.hpp <- gdtk/src/nm/bbla.d),
which keeps the mapping bijective and the reviews diffable. The qualitative
fields (fidelity, variants, verified_by) come from provenance/fidelity.yml,
filled in by whoever did the port.

Usage: gen_manifest.py [path-to-gdtk] > provenance/manifest.yml
"""
import os
import subprocess
import sys

GDTK = sys.argv[1] if len(sys.argv) > 1 else "/home/tang/packages/gdtk"
REPO = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
DEFAULT = {"fidelity": "exact", "variants": [], "verified_by": []}


def read_fidelity_table():
    """Read provenance/fidelity.yml.

    Deliberately a small hand-rolled reader rather than a PyYAML dependency: the
    file is a flat mapping of inline flow records, one line per ported file, and
    the port must be checkable on a machine with nothing installed but python3.
    """
    path = os.path.join(REPO, "provenance", "fidelity.yml")
    table = {}
    if not os.path.exists(path):
        return table
    for raw in open(path, encoding="utf-8"):
        line = raw.rstrip("\n")
        if not line.strip() or line.lstrip().startswith("#"):
            continue
        key, sep, rest = line.partition(":")
        if not sep:
            continue
        key = key.strip()
        rest = rest.strip()
        if not rest.startswith("{"):
            continue
        body = rest.strip("{}")
        record = {}
        # Split on commas that are not inside [ ... ].
        depth, chunk, chunks = 0, "", []
        for ch in body:
            if ch == "[":
                depth += 1
            elif ch == "]":
                depth -= 1
            if ch == "," and depth == 0:
                chunks.append(chunk)
                chunk = ""
            else:
                chunk += ch
        if chunk.strip():
            chunks.append(chunk)
        for item in chunks:
            k, _, v = item.partition(":")
            k, v = k.strip(), v.strip()
            if v.startswith("[") and v.endswith("]"):
                record[k] = [x.strip() for x in v[1:-1].split(",") if x.strip()]
            else:
                record[k] = v
        table[key] = record
    return table


def blob(path):
    out = subprocess.run(["git", "-C", GDTK, "hash-object", "--", path],
                         capture_output=True, text=True)
    return out.stdout.strip() or "UNTRACKED"


def head():
    return subprocess.run(["git", "-C", GDTK, "rev-parse", "HEAD"],
                          capture_output=True, text=True).stdout.strip()


def d_origin(cpp_path):
    """src/nm/bbla.hpp -> <gdtk>/src/nm/bbla.d; substrate/tests -> None."""
    if not cpp_path.startswith("src/"):
        return None
    base = os.path.splitext(cpp_path)[0]
    for ext in (".d",):
        cand = os.path.join(GDTK, base + ext)
        if os.path.exists(cand):
            return base + ext
    return None


def loc(path):
    with open(os.path.join(REPO, path), encoding="utf-8", errors="replace") as fh:
        return sum(1 for _ in fh)


def main():
    table = read_fidelity_table()
    print("# Generated by tools/gen_manifest.py — do not hand-edit.")
    print(f"# gdtk reference HEAD: {head()}")
    print(f"# generated for: {os.path.basename(REPO)}")
    print("files:")
    entries = []
    for root, dirs, files in os.walk(os.path.join(REPO, "src")):
        dirs[:] = [d for d in dirs if d != "retired"]
        for f in sorted(files):
            if not f.endswith((".hpp", ".cpp")):
                continue
            rel = os.path.relpath(os.path.join(root, f), REPO)
            entries.append(rel)
    for rel in sorted(entries):
        origin = d_origin(rel)
        meta = table.get(rel, {})
        rec = dict(DEFAULT)
        rec.update(meta)
        print(f"- cpp: {rel}")
        if origin:
            print(f"  d: {origin}")
            print(f"  d_blob: {blob(origin)}")
            dloc = sum(1 for _ in open(os.path.join(GDTK, origin), encoding="utf-8",
                                       errors="replace"))
            print(f"  d_lines: {dloc}")
        else:
            print("  d: null  # substrate or port-infra, no D counterpart")
        print(f"  cpp_lines: {loc(rel)}")
        print(f"  fidelity: {rec['fidelity']}")
        print(f"  variants: [{', '.join(rec['variants'])}]")
        print(f"  verified_by: [{', '.join(rec['verified_by'])}]")


if __name__ == "__main__":
    main()
