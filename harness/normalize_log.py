#!/usr/bin/env python3
"""Normalize solver output so D and C++ logs can be compared byte-for-byte.

Volatile fields are replaced with placeholders rather than dropped, so a missing
line still shows up as a diff. Each rule exists because that field differs
between two runs of the *same* D binary.
"""
import re
import sys

RULES = [
    (re.compile(r"^Revision-id:.*$"), "Revision-id: <REV>"),
    (re.compile(r"^Revision-date:.*$"), "Revision-date: <REV_DATE>"),
    (re.compile(r"^Compiler-name:.*$"), "Compiler-name: <COMPILER>"),
    (re.compile(r"^Build-date:.*$"), "Build-date: <BUILD_DATE>"),
    (re.compile(r"^Build-flavour:.*$"), "Build-flavour: <FLAVOUR>"),
    # Heap sampling is allocator-specific and differs run to run.
    (re.compile(r"^Heap memory used:.*$"), "<HEAP>"),
    (re.compile(r"wall-clock\(WC\)= [0-9.eE+-]+ sec"), "wall-clock(WC)= <WC> sec"),
    (re.compile(r"\bWC=[0-9.eE+-]+"), "WC=<WC>"),
    (re.compile(r"\bWCtFT=[0-9.eE+-]+"), "WCtFT=<WC>"),
    (re.compile(r"\bWCtMS=[0-9.eE+-]+"), "WCtMS=<WC>"),
    (re.compile(r"\bWCtS=[0-9.eE+-]+"), "WCtS=<WC>"),
    (re.compile(r"elapsed.*$"), "elapsed <ELAPSED>"),
    # prep-gas stamps its generation time into the first line of every gas-model
    # Lua file it writes. Measured across two runs of the same reference binary:
    # 16 of 17 artifacts byte-identical, this line the only difference.
    (re.compile(r"^-- Auto-generated by (\S+) on: .*$"), "-- Auto-generated by \\1 on: <DATE>"),
    # File paths of the reference install leak into Lua error text.
    (re.compile(r"/home/[^\s\"]*/gdtk[^\s\"]*"), "<GDTK_PATH>"),
    (re.compile(r"/home/[^\s\"]*/gdtkinst[^\s\"]*"), "<GDTK_PATH>"),
]


def normalize(text: str) -> str:
    out = []
    for line in text.splitlines():
        line = line.rstrip("\r")
        for pattern, repl in RULES:
            line = pattern.sub(repl, line)
        out.append(line)
    return "\n".join(out) + ("\n" if out else "")


def main() -> int:
    if len(sys.argv) > 1:
        with open(sys.argv[1], encoding="utf-8", errors="replace") as fh:
            sys.stdout.write(normalize(fh.read()))
    else:
        sys.stdout.write(normalize(sys.stdin.read()))
    return 0


if __name__ == "__main__":
    sys.exit(main())
